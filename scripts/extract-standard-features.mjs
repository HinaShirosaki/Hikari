import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, '..');
const sourceDir = path.join(projectRoot, 'Exported Standard Features');
const outputFile = path.join(projectRoot, 'src', 'renderer', 'modules', 'sequence-viewer', 'data', 'exported-standard-features.js');

function normalizeQualifier(value) {
  return String(value || '')
    .replace(/\s+/g, ' ')
    .trim();
}

function extractQuotedQualifier(content, qualifierName) {
  const pattern = new RegExp(`/${qualifierName}="([\\s\\S]*?)"`, 'i');
  const match = content.match(pattern);
  return normalizeQualifier(match?.[1] || '');
}

function extractSequence(content) {
  const match = content.match(/^ORIGIN\s*([\s\S]*?)^\/\/\s*$/m);
  return String(match?.[1] || '')
    .replace(/[^a-z]/gi, '')
    .toUpperCase();
}

function renderModule(records) {
  const rows = records.map((record) => {
    const label = JSON.stringify(record.label);
    const sequence = JSON.stringify(record.sequence);
    return `  Object.freeze({ label: ${label}, sequence: ${sequence} })`;
  });

  return `// Generated by scripts/extract-standard-features.mjs. Do not edit by hand.

export const EXPORTED_STANDARD_FEATURES = Object.freeze([
${rows.join(',\n')}
]);

export default EXPORTED_STANDARD_FEATURES;
`;
}

async function main() {
  const entries = await fs.readdir(sourceDir, { withFileTypes: true });
  const gbkFiles = entries
    .filter((entry) => entry.isFile() && /\.gbk$/i.test(entry.name))
    .map((entry) => entry.name)
    .sort((left, right) => left.localeCompare(right));

  const records = [];

  for (const fileName of gbkFiles) {
    const filePath = path.join(sourceDir, fileName);
    const content = await fs.readFile(filePath, 'utf8');
    const label = extractQuotedQualifier(content, 'label');
    const sequence = extractSequence(content);

    if (!label) {
      throw new Error(`Missing /label in ${fileName}`);
    }

    if (!sequence) {
      throw new Error(`Missing ORIGIN sequence in ${fileName}`);
    }

    records.push({ label, sequence });
  }

  await fs.writeFile(outputFile, renderModule(records), 'utf8');
  console.log(`Extracted ${records.length} standard features to ${outputFile}`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
