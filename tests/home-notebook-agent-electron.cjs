'use strict';
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');
const { pathToFileURL } = require('node:url');
const root = path.resolve(__dirname, '..');
async function main() {
  if (!process.versions.electron) {
    const run = require('node:child_process').spawnSync(require('electron'), [__filename], { encoding: 'utf8', timeout: 60000 });
    process.stdout.write(run.stdout || ''); process.stderr.write(run.stderr || '');
    assert.equal(run.status, 0, String(run.error || run.signal)); return;
  }
  const { app, BrowserWindow } = require('electron');
  const scratch = fs.mkdtempSync(path.join(os.tmpdir(), 'hikari-home-notebook-'));
  app.setPath('userData', path.join(scratch, 'profile'));
  app.disableHardwareAcceleration(); await app.whenReady();
  const url = file => pathToFileURL(path.join(root, file)).href;
  const view = fs.readFileSync(path.join(root, 'ui/html/views/home-view.html'), 'utf8');
  const fixture = path.join(scratch, 'home.html');
  fs.writeFileSync(fixture, `<link rel="stylesheet" href="${url('styles.css')}"><body class="theme-day" data-active-view="home-view">${view}</body>`);
  const win = new BrowserWindow({ width: 1100, height: 850, show: false, webPreferences: { sandbox: true, contextIsolation: true } });
  await win.loadFile(fixture);
  const result = await win.webContents.executeJavaScript(`(async () => {
    const check = (value, message) => { if (!value) throw new Error(message); };
    const { createHomeNotebookAgent } = await import(${JSON.stringify(url('src/renderer/modules/home-dashboard/notebook-agent.js'))});
    const { createSavedNotebookAppend } = await import(${JSON.stringify(url('src/renderer/modules/biology-notebook/agent/saved-append.js'))});
    const originalChat = { messages: [{ role: 'user', text: 'Unrelated chat draft' }] };
    const state = { settings: { storagePath: '', agent: {} }, projects: [{id:'p',name:'GFP'}], protocols: [{id:'r',name:'Expression',steps:[]}], notebookEntries: [{id:'n',projectId:'p',protocolId:'r',experimentName:'GFP expression',result:'Original result',updatedAt:'v1'}], agentChat: originalChat, papers:[], workflows:[], assays:[], gelAnalyses:[], inventory:{},labInventory:{chemicals:[]} };
    let payload; let complete; let saves = 0;
    window.hikariApi = { agentChat: request => { payload = request; return new Promise(resolve => complete = resolve); } };
    const proposal = { proposal_id:'a1',notebook_entry_id:'n',page_title:'GFP expression',expected_updated_at:'v1',content_markdown:'I expressed GFP.' };
    const send = createHomeNotebookAgent({ state, persist:()=>{ saves++; }, createId:()=>crypto.randomUUID(), safeText:text=>String(text??'').replaceAll('&','&amp;').replaceAll('<','&lt;'), rootDocument:document, windowObject:window, rendererServices:{notebook:{handleAgentNotebookEntriesChanged(){}},protocol:{handleProtocolsChanged(){}}},modules:{} });
    let settled = false;
    const request = send('I expressed GFP.').then(value => { settled = true; return value; });
    for (let i=0; i<30 && !complete; i++) await new Promise(resolve=>setTimeout(resolve,10));
    check(complete && !settled, 'Home must wait for completion');
    check(payload.agent.sessionPrompt.includes('notebook_draft'), 'Notebook intent was not supplied');
    check(payload.conversation.every(message=>!message.text?.includes('Unrelated')), 'Home leaked main chat');
    complete({ok:true, notebook_append:{status:'proposal_ready',proposal,save:{mode:'confirm_before_append',applied:false,status:'pending'}}});
    check((await request).ok, 'Home request failed');
    check(state.agentChat === originalChat, 'Main chat was replaced');
    check(document.body.dataset.activeView === 'home-view', 'Navigated away from Home');
    check(state.notebookEntries[0].result === 'Original result', 'Saved before approval');
    const approve = document.querySelector('[data-agent-append-notebook]');
    check(approve && approve.getClientRects().length, 'No visible append approval');
    approve.click();
    for (let i=0; i<30 && state.notebookEntries[0].result === 'Original result'; i++) await new Promise(resolve=>setTimeout(resolve,10));
    check(state.notebookEntries[0].result.includes('I expressed GFP.'), 'Approval did not save');
    check(document.body.dataset.activeView === 'home-view', 'Approval navigated away');
    const saved = state.notebookEntries[0].result;
    const append = createSavedNotebookAppend({state,persist:()=>{}});
    await append(proposal); check(state.notebookEntries[0].result === saved, 'Duplicate proposal appended twice');
    check(!(await append({...proposal,proposal_id:'stale'})).ok, 'Stale proposal accepted');
    const failing = createSavedNotebookAppend({state,persist:()=>{throw Error('disk');}});
    check(!(await failing({...proposal,proposal_id:'fail',expected_updated_at:state.notebookEntries[0].updatedAt})).ok, 'Save failure reported success');
    check(state.notebookEntries[0].result === saved, 'Failed save did not roll back');
    document.getElementById('home-agent-close-btn').click();
    check(document.getElementById('home-agent-overlay').hidden, 'Close failed');
    document.getElementById('home-agent-reopen-btn').click();
    check(!document.getElementById('home-agent-overlay').hidden, 'Resume failed');
    const second = send('More details');
    for (let i=0;i<3;i++) await new Promise(resolve=>setTimeout(resolve,10));
    complete({ok:false,error:'fixture failure'});
    check(!(await second).ok, 'Failed agent call reported success');
    const rect = document.querySelector('.home-agent-dialog').getBoundingClientRect();
    check(rect.width > 300 && rect.bottom <= innerHeight + 1, 'Dialog outside viewport');
    return {saves,width:rect.width,height:rect.height};
  })()`);
  const out = path.join(root, 'artifacts/home-notebook-review'); fs.mkdirSync(out,{recursive:true});
  fs.writeFileSync(path.join(out,'home-notebook.png'), (await win.webContents.capturePage()).toPNG());
  console.log('Home notebook integration passed', result);
  win.destroy(); app.quit();
}
main().catch(error=>{ console.error(error); process.exit(1); });
